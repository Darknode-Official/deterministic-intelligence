// Build the DI concept index — Pillar 1, work-item 6 of the "make DI smart" plan.
//
// Deterministic, offline, re-runnable: load the bundled WordNet list, walk out
// from the hand-picked seeds in src/concepts.js collecting the EXACT verb-sense
// synonyms of each seed (same synset only — no hypernym/hyponym drift), add the
// manual supplement, drop anything ambiguous or already a command, and freeze
// the result into src/concept-index.js (+ .json). Same input -> same output.
//
//   node tools/build-concept-index.mjs
//
// The output is what lets DI understand loose phrasing in Node/CLI/tests without
// loading the 11.8MB lexicon at runtime (concept-lookup.js reads only the index).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadLexicon, synonymsOf, isFunctionWord, COMMANDS } from "../src/lexicon.js";
import { CONCEPTS, MANUAL_TRIGGERS } from "../src/concepts.js";

const ok = await loadLexicon();
if (!ok) { console.error("FAILED: could not load src/lexicon.txt"); process.exit(1); }

const CMD = new Set(COMMANDS);
const norm = (w) => String(w || "").toLowerCase().trim().replace(/[_]/g, " ").replace(/\s+/g, " ");

// trigger -> Set(commands). A trigger wanted by two commands is ambiguous → dropped.
const want = new Map();
const claim = (trigger, command) => {
  const t = norm(trigger);
  if (!t) return;
  if (CMD.has(t)) return;             // already a verb DI acts on — routes on its own
  if (isFunctionWord(t)) return;      // grammar word — never a command
  if (!/^[a-z][a-z' -]*$/.test(t)) return;
  let s = want.get(t); if (!s) want.set(t, (s = new Set()));
  s.add(command);
};

// Triggers we never want, no matter which WordNet sense suggests them: words
// whose everyday meaning in an imperative "do X to this" request is nothing to
// do with the math/text operation (a secondary WordNet sense dragged them in).
const DENY = new Set([
  // secondary-sense drift (unrelated everyday meaning as an imperative verb)
  "breed", "brush up", "carve up", "beget", "sieve", "screen", "fragment", "disunite",
  "part", "separate", "break up", "deal", "hand", "give out", "distribute", "portion",
  "apportion", "manifold", "reckon", "cipher", "cypher",
  // "tally/add-up" also carries an "be in agreement" sense → these are NOT "total"
  "check", "come", "correspond", "fit", "gibe", "jibe", "match", "resume", "amount",
  // "sum up" also means "summarize" (condense text) → NOT numeric total
  "summarise", "summarize",
  // "define" dominant WordNet sense is "delimit/demarcate" → NOT a dictionary lookup
  "delimit", "delimitate", "delineate", "specify",
  // "capitalize" dominant sense is "benefit/capitalize on" → NOT text casing
  "take advantage",
  // other imperative-ambiguous verbs
  "turn", "name", "recite", "work", "work up", "lick", "inscribe"]);

// Seeds expand to their DOMINANT verb sense's synonyms only — the single most
// common WordNet sense. Taking every sense drags in unrelated meanings
// ("multiply" -> breed, "divide" -> carve up); the dominant sense is almost
// always the operation the seed names. This is the plan's over-generalization
// guard made concrete.
for (const { command, seeds } of CONCEPTS) {
  for (const seed of seeds) {
    claim(seed, command);             // the seed itself is always a trigger
    const r = synonymsOf(seed, 24, 8);
    if (!r || !r.ok) continue;
    const top = (r.groups || []).find((g) => g.pos === "verb"); // most-used verb sense
    if (!top) continue;
    for (const w of top.words) if (!DENY.has(norm(w))) claim(w, command);
  }
}

// Hand-authored supplement (phrasings the synset walk does not reach safely).
for (const [trigger, command] of Object.entries(MANUAL_TRIGGERS)) {
  if (!CMD.has(command) && !CONCEPTS.some((c) => c.command === command)) {
    console.error("manual trigger maps to unknown command:", command); process.exit(1);
  }
  claim(trigger, command);
}

// Resolve: keep only unambiguous triggers, sorted for a stable, diffable file.
const index = {};
let dropped = 0;
for (const t of [...want.keys()].sort()) {
  const cmds = [...want.get(t)];
  if (cmds.length === 1) index[t] = cmds[0];
  else dropped++;
}

const count = Object.keys(index).length;
const banner =
  "// GENERATED by tools/build-concept-index.mjs from WordNet + src/concepts.js. Do not edit by hand.\n" +
  "// Re-run: node tools/build-concept-index.mjs  —  deterministic (same input, same output).\n" +
  "// " + count + " loose-phrasing triggers -> DI commands. " + dropped + " ambiguous trigger(s) dropped.\n";

const root = fileURLToPath(new URL("../src/", import.meta.url));
writeFileSync(root + "concept-index.js", banner + "export const CONCEPT_INDEX = " + JSON.stringify(index, null, 0) + ";\n");
writeFileSync(root + "concept-index.json", JSON.stringify(index, Object.keys(index).sort(), 2) + "\n");

console.log("wrote src/concept-index.js and .json:", count, "triggers,", dropped, "ambiguous dropped");
// show a sample so the operator can eyeball it
console.log("sample:", Object.fromEntries(Object.entries(index).slice(0, 20)));
